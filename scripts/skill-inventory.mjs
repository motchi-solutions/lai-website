#!/usr/bin/env node
// Regenerates docs/SKILLS.md from .agents/skills/*/SKILL.md and skills-lock.json.
// Purpose cells and everything below the "Notes" heading are kept between runs.
// Offline: reads local files only. Usage: node scripts/skill-inventory.mjs
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const skillsDir = path.join(root, ".agents", "skills");
const outFile = path.join(root, "docs", "SKILLS.md");
const cell = (s) =>
    String(s ?? "")
        .replaceAll("|", "\\|")
        .replace(/\s+/g, " ")
        .trim();

const old = existsSync(outFile) ? readFileSync(outFile, "utf8") : "";
const purposes = new Map();
for (const line of old.split("\n")) {
    const m = line.match(/^\| \[([^\]]+)\]\([^)]*\) \|.*\| ([^|]*) \|$/);
    if (m && m[2].trim()) purposes.set(m[1], m[2].trim());
}
const notesAt = old.indexOf("\n## Notes");
const notes =
    notesAt >= 0
        ? old.slice(notesAt + 1).trimEnd()
        : "## Notes\n\nAdd lasting notes here (provenance pins, local changes, extra cautions). This section is kept when the file is regenerated.";

const lock = existsSync(path.join(root, "skills-lock.json"))
    ? (JSON.parse(readFileSync(path.join(root, "skills-lock.json"), "utf8")).skills ?? {})
    : {};

function files(dir, base = dir, acc = []) {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) files(full, base, acc);
        else acc.push(path.relative(base, full));
    }
    return acc;
}
// A helper is a script file, or an extensionless executable (like a CLI wrapper).
const isHelper = (dir, f) =>
    /\.(m?js|cjs|ts|py|sh|rb)$/.test(f) ||
    (!path.extname(f) && (statSync(path.join(dir, f)).mode & 0o111) !== 0);
const NET =
    /\bfetch\(|https?:\/\/(?!(www\.)?(github\.com|opensource\.org|spdx\.org|creativecommons\.org)\/)|\bcurl\b|\bwget\b|XMLHttpRequest|require\(["']https?["']\)|from ["']node:https?["']|puppeteer|playwright|\bnpx\b/;

const rows = [];
const names = existsSync(skillsDir)
    ? readdirSync(skillsDir)
          .filter((n) => existsSync(path.join(skillsDir, n, "SKILL.md")))
          .sort()
    : [];
for (const name of names) {
    const dir = path.join(skillsDir, name);
    const md = readFileSync(path.join(dir, "SKILL.md"), "utf8");
    const front = md.match(/^---\n([\s\S]*?)\n---/)?.[1] ?? "";
    const desc = (front.match(/^description:\s*[>|]?-?\s*([\s\S]*?)(?=\n[\w-]+:|$)/m)?.[1] ?? "")
        .trim()
        .replace(/^["']|["']$/g, "");
    const helpers = files(dir).filter((f) => isHelper(dir, f));
    const network = helpers.filter((f) => NET.test(readFileSync(path.join(dir, f), "utf8")));
    const source = lock[name]?.source
        ? `[${lock[name].source}](https://github.com/${lock[name].source})`
        : "see Notes";
    const license = files(dir).find((f) => /^LICEN[CS]E/i.test(f))
        ? `[yes](../.agents/skills/${name}/${files(dir).find((f) => /^LICEN[CS]E/i.test(f))})`
        : "none bundled";
    const helperCell = helpers.length
        ? `${helpers.length}: ${helpers
              .slice(0, 4)
              .map((h) => `\`${h}\``)
              .join(", ")}${helpers.length > 4 ? ", ..." : ""}`
        : "none (instructions only)";
    const netCell = network.length
        ? `**possible**: ${network
              .slice(0, 3)
              .map((h) => `\`${h}\``)
              .join(", ")}`
        : "no network code found";
    rows.push(
        `| [${name}](../.agents/skills/${name}/SKILL.md) | ${source} | ${license} | ${helperCell} | ${netCell} | ${cell(purposes.get(name) ?? desc.slice(0, 160) + (desc.length > 160 ? "..." : ""))} |`,
    );
}

const out = [
    "# Skill tracker",
    "",
    `Generated by \`node scripts/skill-inventory.mjs\` on ${new Date().toISOString().slice(0, 10)}. Edit only the Purpose column and the Notes section; the rest is rebuilt from \`.agents/skills/\` and \`skills-lock.json\`.`,
    "",
    "Helpers are bundled scripts. Network means the script text contains network code; it is a hint, not a review. Installing or reading a skill never allows running its helpers or making network calls (see AGENTS.md).",
    "",
];
if (rows.length)
    out.push(
        "| Skill | Source | License | Helpers | Network | Purpose |",
        "| --- | --- | --- | --- | --- | --- |",
        ...rows,
        "",
    );
else out.push("No skills installed in `.agents/skills/`.", "");
out.push(notes, "");
writeFileSync(outFile, out.join("\n"));
console.log(`Updated docs/SKILLS.md: ${rows.length} skills`);
